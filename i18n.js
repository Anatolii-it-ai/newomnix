const LANGS = ['ru', 'ro', 'en'];
const LANG_LABELS = { ru: 'RU', ro: 'RO', en: 'EN' };
const FALLBACK_LANG = 'ru';

function detectLang() {
  const stored = localStorage.getItem('omx-lang');
  if (stored && LANGS.includes(stored)) return stored;
  const nav = (navigator.language || '').slice(0, 2).toLowerCase();
  return LANGS.includes(nav) ? nav : FALLBACK_LANG;
}

let CURRENT_LANG = detectLang();

function getNested(obj, path) {
  return path.split('.').reduce((o, k) => (o == null ? o : o[k]), obj);
}

function interpolate(s, vars) {
  if (!vars || typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
}

window.t = function t(key, vars) {
  const v = getNested(TRANSLATIONS[CURRENT_LANG], key);
  if (typeof v === 'string') return interpolate(v, vars);
  if (typeof v !== 'undefined') return v; // объект/число — возвращаем как есть
  // fallback to RU
  const fb = getNested(TRANSLATIONS[FALLBACK_LANG], key);
  if (typeof fb === 'string') return interpolate(fb, vars);
  if (typeof fb !== 'undefined') return fb;
  return key;
};

window.getLang = function getLang() { return CURRENT_LANG; };

window.setLang = function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  CURRENT_LANG = lang;
  localStorage.setItem('omx-lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  // оповещаем страницу — она может перерендерить динамические виджеты
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
};

window.applyTranslations = function applyTranslations(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
};

