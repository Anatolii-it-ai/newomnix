// Translate sphere name (storage key in Russian) to current locale
window.tSphere = function tSphere(ruName) {
  if (!ruName) return ruName;
  const map = TRANSLATIONS[CURRENT_LANG]?.spheres || {};
  return map[ruName] || ruName;
};

// Translate quadrant label (1..4)
window.tQuadrant = function tQuadrant(q) {
  return TRANSLATIONS[CURRENT_LANG]?.quadrants?.[q] || TRANSLATIONS[FALLBACK_LANG].quadrants[q] || '';
};

// Render the language switcher into a given container.
// Принимает <select> или произвольный контейнер.
window.renderLangSwitcher = function renderLangSwitcher(target) {
  const el = typeof target === 'string' ? document.getElementById(target) : target;
  if (!el) return;
  el.innerHTML = LANGS.map(l => `<option value="${l}"${l === CURRENT_LANG ? ' selected' : ''}>${LANG_LABELS[l]}</option>`).join('');
  el.addEventListener('change', () => setLang(el.value));
};

